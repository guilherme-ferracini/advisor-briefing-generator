"""Builds a personalised daily briefing per advisor: a short spoken-style script
plus talking points per client. Portfolio facts come from code; the LLM connects
them to the market context."""

from __future__ import annotations

import json
from typing import Dict

from .llm import LLMClient
from .portfolio import AdvisorView

SYSTEM = (
    "You write daily briefings for investment advisors at a Brazilian brokerage office. "
    "Output two parts. PART 1: a spoken-style script of at most 150 words, addressed to the "
    "advisor by first name, connecting today's market notes to their book. PART 2: one or "
    "two talking points per client, prioritising alerts. Use only the facts provided; never "
    "recommend specific securities and never promise returns. Write in English."
)


def advisor_payload(view: AdvisorView) -> Dict:
    return {
        "advisor": view.advisor,
        "aum_brl": round(view.aum),
        "maturing_next_30_days_brl": round(view.maturing_total),
        "clients": [
            {
                "client": c.client_name,
                "profile": c.risk_profile,
                "total_brl": round(c.total),
                "allocation": {k: f"{v / c.total:.0%}" for k, v in c.by_class.items()},
                "alerts": c.alerts,
            }
            for c in view.clients
        ],
    }


def mock_briefing(_system: str, prompt: str) -> str:
    data = json.loads(prompt.split("BOOK:", 1)[1])
    first = data["advisor"].split()[0]
    alerts = [(c["client"], a) for c in data["clients"] for a in c["alerts"]]
    script = (
        f"Good morning, {first}. Your book is at R$ {data['aum_brl']:,.0f} across "
        f"{len(data['clients'])} clients, with R$ {data['maturing_next_30_days_brl']:,.0f} maturing in the next 30 days. "
        f"Today you have {len(alerts)} alerts to work through. Start with the maturities: that is where "
        f"reinvestment conversations happen."
    )
    lines = ["PART 1 - Script", script, "", "PART 2 - Talking points"]
    for c in data["clients"]:
        points = c["alerts"] or ["No alerts. A good moment for a relationship call."]
        lines.append(f"- {c['client']} ({c['profile']}, R$ {c['total_brl']:,.0f}): " + " ".join(points))
    lines.append("\n(Demo mode: generated by rules. Use --provider anthropic or openai for an AI-written briefing.)")
    return "\n".join(lines)


def generate(view: AdvisorView, market_notes: str, client: LLMClient) -> str:
    prompt = (
        "Market notes for today:\n" + market_notes.strip() +
        "\n\nWrite the briefing for this advisor.\nBOOK:" + json.dumps(advisor_payload(view))
    )
    return client.complete(SYSTEM, prompt, max_tokens=900)
